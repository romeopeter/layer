import { useEffect, useMemo, useRef, useState } from "react";
import { Search } from "lucide-react";
import type { BrandKit, FontFile, FontWeight } from "@/types/brand";
import { useEditor } from "@/store/editor";
import { cn } from "@/lib/utils";
import { downloadGoogleFont } from "@/lib/host";
import { registerFont } from "@/lib/fonts/registry";
import { WEIGHT_NAMES } from "@/lib/fonts/files";
import { isLayerFont, withFont } from "@/lib/brand/kits";
import { AppModal } from "@/components/ui/app-modal";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { ToggleGroup, ToggleGroupItem } from "@/components/ui/toggle-group";
import { PanelHelp } from "./primitives";
import { choiceClass } from "./choice";

interface GoogleFont {
  family: string;
  category: string;
  weights: FontWeight[];
}

const CATEGORIES = [
  { key: "all", label: "All" },
  { key: "sans-serif", label: "Sans" },
  { key: "serif", label: "Serif" },
  { key: "display", label: "Display" },
  { key: "handwriting", label: "Hand" },
  { key: "monospace", label: "Mono" },
];

/** Enough to scan, in popularity order, without drawing the whole catalogue. */
const SHOWN = 40;
const ALL_WEIGHTS: FontWeight[] = [400, 500, 700];
/** What Google's names are made of. A typed name is tried only if it could be one. */
const PLAIN_NAME = /^[A-Za-z0-9]+( [A-Za-z0-9]+)*$/;

const PREVIEW = "Brand new visuals, ready to ship";

type Preview =
  | { family: string; state: "loading" }
  | { family: string; state: "ready" }
  | { family: string; state: "failed"; message: string };

/** The fonts list, generated by `npm run fonts:sync` and loaded with the picker. */
const useGoogleFonts = (open: boolean) => {
  const [fonts, setFonts] = useState<GoogleFont[] | null>(null);
  useEffect(() => {
    if (!open || fonts) return;
    let current = true;
    void import("@/data/googleFonts.json").then((module) => current && setFonts(module.default as GoogleFont[]));
    return () => {
      current = false;
    };
  }, [open, fonts]);
  return fonts;
};

/** Search Google Fonts, see one in use, and add it to the kit in Regular, Medium and Bold. */
export const GoogleFontPicker = ({
  kit,
  open,
  onOpenChange,
}: {
  kit: BrandKit;
  open: boolean;
  onOpenChange: (open: boolean) => void;
}) => {
  const update = useEditor((s) => s.updateBrandKit);
  const fonts = useGoogleFonts(open);
  const [query, setQuery] = useState("");
  const [category, setCategory] = useState("all");
  const [preview, setPreview] = useState<Preview | null>(null);
  const [adding, setAdding] = useState(false);
  const [problem, setProblem] = useState<string | null>(null);
  // Files already downloaded this session, so adding doesn't fetch them twice.
  const files = useRef(new Map<string, string>());
  const chosen = useRef<string | null>(null);

  const typed = query.trim();
  const matches = useMemo(() => {
    const words = typed.toLowerCase();
    return (fonts ?? [])
      .filter((font) => (category === "all" || font.category === category) && font.family.toLowerCase().includes(words))
      .slice(0, SHOWN);
  }, [fonts, typed, category]);
  // A name typed in full that isn't in the list (or with no list yet) can still be tried.
  const canTry =
    PLAIN_NAME.test(typed) &&
    !isLayerFont(typed) &&
    !matches.some((font) => font.family.toLowerCase() === typed.toLowerCase());

  const weightsOf = (family: string) => fonts?.find((font) => font.family === family)?.weights ?? ALL_WEIGHTS;

  const download = async (family: string, weight: FontWeight) => {
    const key = `${family}|${weight}`;
    const known = files.current.get(key);
    if (known) return known;
    const src = await downloadGoogleFont(family, weight);
    files.current.set(key, src);
    return src;
  };

  const choose = async (family: string) => {
    chosen.current = family;
    setProblem(null);
    setPreview({ family, state: "loading" });
    const weight = weightsOf(family)[0];
    try {
      const src = await download(family, weight);
      await registerFont({ family, weight, src });
      if (chosen.current === family) setPreview({ family, state: "ready" });
    } catch (error) {
      if (chosen.current === family) {
        setPreview({ family, state: "failed", message: error instanceof Error ? error.message : String(error) });
      }
    }
  };

  const add = async () => {
    if (preview?.state !== "ready") return;
    const { family } = preview;
    setAdding(true);
    setProblem(null);
    // Every weight Layer uses that the font has. A typed name tries all three.
    const got: FontFile[] = [];
    for (const weight of weightsOf(family)) {
      try {
        got.push({ weight, src: await download(family, weight) });
      } catch {
        // A weight it doesn't have is left out.
      }
    }
    setAdding(false);
    if (got.length === 0) {
      setProblem("Layer couldn't download that font. Try again in a moment.");
      return;
    }
    const latest = useEditor.getState().brandKits.find((entry) => entry.id === kit.id) ?? kit;
    update(kit.id, { fonts: withFont(latest, { family, source: "google", files: got }) });
    onOpenChange(false);
  };

  const inKit = (family: string) => kit.fonts.some((font) => font.family === family);

  return (
    <AppModal
      open={open}
      onOpenChange={onOpenChange}
      title="Add from Google Fonts"
      description="Fonts are downloaded into your kit, so they work offline and travel with your projects."
      className="max-w-lg"
    >
      <div className="space-y-2.5">
        <div className="relative">
          <Search className="pointer-events-none absolute left-2.5 top-1/2 h-3.5 w-3.5 -translate-y-1/2 text-text-faint" />
          <Input
            aria-label="Search Google Fonts"
            placeholder={fonts?.length ? "Search fonts" : "Type a font's name, as Google Fonts shows it"}
            className="pl-8"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
          />
        </div>
        {fonts && fonts.length > 0 && (
          <ToggleGroup
            type="single"
            aria-label="Font category"
            value={category}
            onValueChange={(v) => v && setCategory(v)}
            className="w-full"
          >
            {CATEGORIES.map((entry) => (
              <ToggleGroupItem key={entry.key} value={entry.key} className="cursor-pointer px-1">
                {entry.label}
              </ToggleGroupItem>
            ))}
          </ToggleGroup>
        )}

        <div role="listbox" aria-label="Google Fonts" className="max-h-56 space-y-1 overflow-y-auto overscroll-contain">
          {canTry && (
            <button
              type="button"
              role="option"
              aria-selected={preview?.family === typed}
              onClick={() => void choose(typed)}
              className={cn(
                "flex w-full cursor-pointer items-center justify-between rounded-md border bg-chrome/40 px-2.5 py-1.5 text-left text-[12px] text-text",
                choiceClass(preview?.family === typed),
              )}
            >
              Try “{typed}”
            </button>
          )}
          {matches.map((font) => (
            <button
              key={font.family}
              type="button"
              role="option"
              aria-selected={preview?.family === font.family}
              onClick={() => void choose(font.family)}
              className={cn(
                "flex w-full cursor-pointer items-center justify-between gap-2 rounded-md border bg-chrome/40 px-2.5 py-1.5 text-left",
                choiceClass(preview?.family === font.family),
              )}
            >
              <span className="truncate text-[12px] text-text">{font.family}</span>
              <span className="shrink-0 text-[10px] text-text-muted">
                {inKit(font.family) ? "In your kit" : font.weights.map((weight) => WEIGHT_NAMES[weight]).join(", ")}
              </span>
            </button>
          ))}
          {fonts && matches.length === 0 && !canTry && (
            <PanelHelp>{fonts.length ? "No font by that name." : "Type the name of a font from fonts.google.com."}</PanelHelp>
          )}
        </div>

        {preview && (
          <div className="space-y-1 rounded-md border border-hairline bg-chrome/40 p-3" aria-live="polite">
            {preview.state === "ready" ? (
              <p className="m-0 text-[22px] leading-tight text-text" style={{ fontFamily: `"${preview.family}"` }}>
                {PREVIEW}
              </p>
            ) : (
              <PanelHelp className={cn("m-0", preview.state === "failed" && "text-a-200")}>
                {preview.state === "loading" ? `Downloading ${preview.family}…` : preview.message}
              </PanelHelp>
            )}
          </div>
        )}
        {problem && <PanelHelp className="text-a-200">{problem}</PanelHelp>}

        <div className="flex items-center justify-between gap-2 pt-1">
          <span className="text-[10.5px] text-text-faint">Fonts from Google Fonts, free to use commercially.</span>
          <Button
            variant="primary"
            size="sm"
            className="cursor-pointer"
            disabled={preview?.state !== "ready" || adding}
            onClick={() => void add()}
          >
            {adding ? "Adding…" : preview && inKit(preview.family) ? "Add again" : "Add to kit"}
          </Button>
        </div>
      </div>
    </AppModal>
  );
};
